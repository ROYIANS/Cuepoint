async function run(label, only, expected) {
  const directory = path.join(output, `${String(++sequence).padStart(2, '0')}-${label}`);
  await mkdir(directory);
  const source = {};
  for (const dir of ['src', 'tests', 'quality', 'contract-evidence']) {
    let files = [];
    try { files = await filesUnder(fixture, dir); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    for (const file of files) source[file] = await readFile(path.join(fixture, file), 'utf8');
  }
  for (const file of ['package.json', 'tsconfig.app.json', 'tsconfig.json', 'eslint.config.mjs', 'knip.json']) source[file] = await readFile(path.join(fixture, file), 'utf8');
  const producerFiles = ['scripts/quality-check.mjs', ...await filesUnder(project, 'scripts/quality')];
  const producerSources = Object.fromEntries(await Promise.all(producerFiles.map(async file => [file, await readFile(path.join(project, file), 'utf8')])));
  const producerHashes = Object.fromEntries(Object.entries(producerSources).map(([file, text]) => [file, hash(text)]));
  assert.deepEqual(producerHashes, initialProducer, 'Quality producer changed during self-test; rerun on frozen code');
  await writeFile(path.join(directory, 'inputs.json'), JSON.stringify({ files: source, producerSources, producerHashes, hashes: Object.fromEntries(Object.entries(source).map(([file, text]) => [file, hash(text)])) }, null, 2));
  const command = await runCommand(process.execPath, [commandFile, '--root', fixture, ...(only ? ['--only', only] : []), '--report', path.join(directory, 'report.json')], project);
  await writeFile(path.join(directory, 'command.json'), JSON.stringify(command, null, 2));
  const report = JSON.parse(await readFile(path.join(directory, 'report.json'), 'utf8'));
  cases.push({ label, only: only ?? 'all', expected, actual: command.exitCode, directory: path.basename(directory), reportSHA256: hash(JSON.stringify(report)) });
  console.log(`${label}: exit ${command.exitCode} (expected ${expected})`);
  assert.equal(command.exitCode, expected, `${label}: ${command.stderr}\n${command.stdout}`);
  return report;
}
