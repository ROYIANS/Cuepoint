    const key = JSON.stringify([row.rule, row.file, row.signature]);
    const prior = grouped.get(key);
    if (prior) prior.count++;
    else grouped.set(key, { rule: row.rule, file: row.file, signature: row.signature, count: 1, reason: 'Synthetic reviewed object throw fixture only', owner: 'Quality gate self-test' });
